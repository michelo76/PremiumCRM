local T = ...
local FakeDeps = require("fake_deps")
local Roku = require("np.providers.roku")

local function setup(app, player, opts)
  opts = opts or {}
  local fd = FakeDeps.new()
  fd:route("/query/device-info", { status = 200, body = T.fixture(opts.device or "roku_device_info.xml") })
  fd:route("/query/active-app", { status = 200, body = T.fixture(app) })
  if player then fd:route("/query/media-player", { status = 200, body = T.fixture(player) }) end
  fd:route("/query/tv-active-channel", { status = 200, body = T.fixture("roku_tv_active_channel.xml") })
  local p = Roku.new({ host = "192.168.1.50", group = "lr" }, fd.deps)
  return fd, p
end

local function poll(fd, p)
  local res = {}
  p:poll(function(err, pb) res.err, res.pb = err, pb end)
  fd:flush()
  return res.err, res.pb
end

describe("np.providers.roku", function()
  it("maps a playing Netflix stream honestly (no title)", function()
    local fd, p = setup("roku_active_app_netflix.xml", "roku_media_player_play.xml")
    local err, pb = poll(fd, p)
    T.is_nil(err)
    T.eq(pb.source.provider, "roku"); T.eq(pb.source.device_name, "Living Room Roku")
    T.eq(pb.source.app_name, "Netflix"); T.eq(pb.source.app_id, "12")
    T.eq(pb.source.app_icon_url, "http://192.168.1.50:8060/query/icon/12")
    T.eq(pb.playback.state, "playing"); T.near(pb.playback.position_s, 1234.567); T.eq(pb.playback.duration_s, 2071)
    T.eq(pb.playback.is_live, false); T.eq(pb.playback.position_updated_at, fd.t)
    T.eq(pb.media.kind, "video"); T.is_nil(pb.media.title)
    T.eq(p.id, "roku:192.168.1.50"); T.eq(p.group, "lr")
  end)
  it("maps pause and live", function()
    local fd, p = setup("roku_active_app_netflix.xml", "roku_media_player_pause.xml")
    local _, pb = poll(fd, p)
    T.eq(pb.playback.state, "paused"); T.eq(pb.playback.position_s, 1240)
    fd, p = setup("roku_active_app_netflix.xml", "roku_media_player_live.xml")
    _, pb = poll(fd, p)
    T.eq(pb.playback.is_live, true)
  end)
  it("app open but nothing playing -> idle", function()
    local fd, p = setup("roku_active_app_netflix.xml", "roku_media_player_none.xml")
    local _, pb = poll(fd, p)
    T.eq(pb.playback.state, "idle"); T.eq(pb.source.app_name, "Netflix"); T.eq(pb.media.kind, "unknown")
  end)
  it("home screen and screensaver -> idle without querying media-player", function()
    local fd, p = setup("roku_active_app_home.xml", nil)
    local _, pb = poll(fd, p)
    T.eq(pb.playback.state, "idle"); T.eq(pb.source.app_name, "Roku")
    T.eq(fd:count("media-player"), 0)
    fd, p = setup("roku_active_app_screensaver.xml", nil)
    _, pb = poll(fd, p)
    T.eq(pb.playback.state, "idle"); T.eq(pb.source.app_name, "Roku Digital Clock")
  end)
  it("tuner input -> live_tv with channel and program", function()
    local fd, p = setup("roku_active_app_dtv.xml", nil)
    local _, pb = poll(fd, p)
    T.eq(pb.media.kind, "live_tv"); T.eq(pb.media.channel_number, "7.1"); T.eq(pb.media.channel_name, "WJLA-HD")
    T.eq(pb.media.title, "ABC World News Tonight With David Muir")
    T.eq(pb.media.subtitle, "Breaking news & top stories from around the world.")
    T.eq(pb.playback.is_live, true); T.eq(pb.playback.state, "playing")
  end)
  it("HDMI input -> playing, unknown content", function()
    local fd, p = setup("roku_active_app_hdmi.xml", nil)
    local _, pb = poll(fd, p)
    T.eq(pb.playback.state, "playing"); T.eq(pb.media.kind, "unknown"); T.eq(pb.source.app_name, "Xbox")
  end)
  it("standby TV -> off", function()
    local fd, p = setup("roku_active_app_netflix.xml", "roku_media_player_play.xml", { device = "roku_device_info_off.xml" })
    local _, pb = poll(fd, p)
    T.eq(pb.playback.state, "off"); T.eq(fd:count("active-app"), 0)
  end)
  it("caches device-info while powered on", function()
    local fd, p = setup("roku_active_app_netflix.xml", "roku_media_player_play.xml")
    poll(fd, p); fd:advance(2); poll(fd, p)
    T.eq(fd:count("device-info"), 1)
    fd:advance(11); poll(fd, p)
    T.eq(fd:count("device-info"), 2)
  end)
  it("surfaces a clear 403 error", function()
    local fd = FakeDeps.new()
    fd:route("/query/", { status = 403, body = "" })
    local p = Roku.new({ host = "10.0.0.2" }, fd.deps)
    local err = poll(fd, p)
    T.contains(err, "Control by mobile apps")
  end)
  it("reports unreachable and bad xml", function()
    local fd = FakeDeps.new()
    fd:route("/query/", { err = "timeout" })
    local p = Roku.new({ host = "10.0.0.2" }, fd.deps)
    T.contains(poll(fd, p), "unreachable")
    fd:route("/query/", { status = 200, body = "<device-info><oops></device-info>" })
    T.contains(poll(fd, p), "mismatched")
  end)
  it("config name overrides device name", function()
    local fd = FakeDeps.new()
    fd:route("/query/device-info", { status = 200, body = T.fixture("roku_device_info.xml") })
    fd:route("/query/active-app", { status = 200, body = T.fixture("roku_active_app_home.xml") })
    local p = Roku.new({ host = "h", name = "Den" }, fd.deps)
    local _, pb = poll(fd, p)
    T.eq(pb.source.device_name, "Den")
  end)
end)
