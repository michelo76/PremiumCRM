local T = ...
local FakeDeps = require("fake_deps")
local Bridge = require("np.providers.bridge")
local Static = require("np.providers.static")
local factory = require("np.providers.factory")

local function poll(fd, p)
  local r = {}
  p:poll(function(err, pb) r.err, r.pb = err, pb end)
  fd:flush()
  return r.err, r.pb
end

describe("np.providers.bridge", function()
  it("accepts the pyatv bridge document", function()
    local fd = FakeDeps.new()
    fd:route("/v1/devices/den/now-playing", { status = 200, body = T.fixture("bridge_appletv.json") })
    local p = Bridge.new({ url = "http://10.0.0.5:8765/v1/devices/den/now-playing" }, fd.deps)
    local err, pb = poll(fd, p)
    T.is_nil(err)
    T.eq(pb.source.provider, "appletv"); T.eq(pb.source.device_name, "Den Apple TV")
    T.eq(pb.playback.position_s, 3021.4); T.eq(pb.playback.position_updated_at, 1790000000.5)
    T.eq(pb.playback.volume, 30)
    T.eq(pb.media.kind, "movie"); T.eq(pb.media.year, 2022); T.deep_eq(pb.media.genres, { "Action", "Drama" })
    T.is_nil(pb.source.app_icon_url)
  end)
  it("rejects documents without playback and garbage", function()
    local fd = FakeDeps.new()
    fd:route("/np", FakeDeps.json({ hello = "world" }))
    local p = Bridge.new({ url = "http://b/np" }, fd.deps)
    T.contains(poll(fd, p), "not a playback document")
    fd:route("/np", { status = 200, body = "not json" })
    T.contains(poll(fd, p), "invalid JSON")
    fd:route("/np", { status = 503, body = "" })
    T.contains(poll(fd, p), "503")
  end)
  it("uses provider_name and name defaults", function()
    local fd = FakeDeps.new()
    fd:route("/np", FakeDeps.json({ playback = { state = "paused" }, media = { title = "X" } }))
    local p = Bridge.new({ url = "http://b/np", provider_name = "appletv", name = "Bedroom ATV" }, fd.deps)
    local _, pb = poll(fd, p)
    T.eq(pb.source.provider, "appletv"); T.eq(pb.source.device_name, "Bedroom ATV"); T.eq(pb.playback.state, "paused")
  end)
end)

describe("np.providers.static", function()
  it("is off until pushed, then returns sanitized copies", function()
    local fd = FakeDeps.new()
    local p = Static.new({ id = "c4room", name = "Family Room" }, fd.deps)
    local _, pb = poll(fd, p)
    T.eq(pb.playback.state, "off"); T.eq(pb.source.provider, "c4room")
    local updates = 0
    p.on_update = function() updates = updates + 1 end
    p:push({ playback = { state = "playing" }, media = { kind = "music", title = "Song", artist = "A" },
      source = { app_name = "TuneIn" } })
    T.eq(updates, 1)
    local _, pb2 = poll(fd, p)
    T.eq(pb2.playback.state, "playing"); T.eq(pb2.media.title, "Song"); T.eq(pb2.source.provider, "c4room")
    T.eq(pb2.source.device_name, "Family Room")
    pb2.media.title = "mutated"
    local _, pb3 = poll(fd, p)
    T.eq(pb3.media.title, "Song")
    p:clear()
    local _, pb4 = poll(fd, p)
    T.eq(pb4.playback.state, "off"); T.eq(updates, 2)
  end)
  it("expires stale pushes with max_age_s", function()
    local fd = FakeDeps.new()
    local p = Static.new({ id = "c4room", max_age_s = 60 }, fd.deps)
    p:push({ playback = { state = "playing" } })
    fd:advance(61)
    local _, pb = poll(fd, p)
    T.eq(pb.playback.state, "off")
  end)
end)

describe("np.providers.factory", function()
  it("creates by type and reports errors", function()
    local fd = FakeDeps.new()
    T.eq(factory.create({ type = "roku", host = "h" }, fd.deps).kind, "roku")
    T.eq(factory.create({ type = "ha", base_url = "http://h", entity_id = "m.x" }, fd.deps).kind, "homeassistant")
    T.eq(factory.create({ type = "static" }, fd.deps).kind, "static")
    local p, err = factory.create({ type = "zune" }, fd.deps)
    T.is_nil(p); T.contains(err, "unknown provider")
    p, err = factory.create({ type = "roku" }, fd.deps)
    T.is_nil(p); T.contains(err, "host")
  end)
end)
