local T = ...
local FakeDeps = require("fake_deps")
local HA = require("np.providers.homeassistant")

local function setup(fixture, cfg, status)
  local fd = FakeDeps.new()
  fd:route("/api/states/", { status = status or 200, body = fixture and T.fixture(fixture) or "" })
  cfg = cfg or {}
  cfg.base_url = cfg.base_url or "http://ha.local:8123/"
  cfg.token = cfg.token or "TOKEN"
  cfg.entity_id = cfg.entity_id or "media_player.living_room_apple_tv"
  return fd, HA.new(cfg, fd.deps)
end

local function poll(fd, p)
  local r = {}
  p:poll(function(err, pb) r.err, r.pb = err, pb end)
  fd:flush()
  return r.err, r.pb
end

describe("np.providers.homeassistant", function()
  it("maps an Apple TV episode", function()
    local fd, p = setup("ha_appletv_episode.json", { provider_name = "appletv" })
    local err, pb = poll(fd, p)
    T.is_nil(err)
    local req = fd:last("/api/states/")
    T.eq(req.url, "http://ha.local:8123/api/states/media_player.living_room_apple_tv")
    T.eq(req.headers.Authorization, "Bearer TOKEN")
    T.eq(pb.source.provider, "appletv"); T.eq(pb.source.device_name, "Living Room Apple TV")
    T.eq(pb.source.app_name, "Hulu"); T.eq(pb.source.app_id, "com.hulu.plus")
    T.eq(pb.playback.state, "playing"); T.eq(pb.playback.position_s, 600); T.eq(pb.playback.duration_s, 2460)
    T.near(pb.playback.position_updated_at, 1790000000 - 60 + 0.123456, 1e-5)
    T.eq(pb.playback.volume, 45)
    T.eq(pb.media.kind, "episode"); T.eq(pb.media.series_title, "The Bear")
    T.eq(pb.media.season, 2); T.eq(pb.media.episode, 7)
    T.eq(pb.media.title, "Forks"); T.eq(pb.media.episode_title, "Forks")
    T.eq(pb.media.artwork_url, "http://ha.local:8123/api/media_player_proxy/media_player.living_room_apple_tv?token=0123abcd&cache=9f8e7d")
    T.is_nil(pb.source.app_icon_url)
  end)
  it("maps Sonos music with absolute artwork and source fallback", function()
    local fd, p = setup("ha_sonos_music.json", { entity_id = "media_player.kitchen" })
    local _, pb = poll(fd, p)
    T.eq(pb.source.provider, "homeassistant"); T.eq(pb.source.app_name, "Spotify")
    T.eq(pb.media.kind, "music"); T.eq(pb.media.artist, "The Weeknd"); T.eq(pb.media.album, "After Hours")
    T.eq(pb.media.track_number, 9); T.eq(pb.playback.volume, 22)
    T.eq(pb.media.artwork_url, "https://i.scdn.co/image/ab67616d0000b2738863bc11d2aa12b54f5aeb36")
    T.eq(pb.playback.position_updated_at, 1790000000 - 20)
  end)
  it("off: no media, not an error", function()
    local fd, p = setup("ha_off.json")
    local err, pb = poll(fd, p)
    T.is_nil(err); T.eq(pb.playback.state, "off"); T.is_nil(pb.media.title); T.is_nil(pb.media.artwork_url)
  end)
  it("HA Roku app without title: picture is the app icon", function()
    local fd, p = setup("ha_roku_app.json", { entity_id = "media_player.living_room_roku" })
    local _, pb = poll(fd, p)
    T.eq(pb.media.kind, "unknown"); T.is_nil(pb.media.title); T.is_nil(pb.media.artwork_url)
    T.contains(pb.source.app_icon_url, "http://ha.local:8123/api/media_player_proxy/media_player.living_room_roku")
    T.eq(pb.source.app_name, "Netflix")
    T.eq(pb.playback.position_updated_at, 1790000000 - 2, "non-UTC offset")
  end)
  it("picture_is_app_icon=false forces artwork", function()
    local fd, p = setup("ha_roku_app.json", { picture_is_app_icon = false })
    local _, pb = poll(fd, p)
    T.ok(pb.media.artwork_url); T.is_nil(pb.source.app_icon_url)
  end)
  it("title present -> picture is artwork; movie kind", function()
    local fd, p = setup("ha_movie_title.json")
    local _, pb = poll(fd, p)
    T.eq(pb.media.kind, "movie"); T.eq(pb.media.title, "Top Gun: Maverick")
  end)
  it("state mapping", function()
    local cases = { { "on", nil, "idle" }, { "on", "Something", "playing" }, { "standby", nil, "off" },
      { "unavailable", nil, "off" }, { "unknown", nil, "off" }, { "buffering", nil, "buffering" },
      { "idle", nil, "idle" }, { "paused", nil, "paused" } }
    for _, c in ipairs(cases) do
      local pb = HA.map_entity({ state = c[1], attributes = { media_title = c[2] } }, "http://h", {}, 0)
      T.eq(pb.playback.state, c[3], c[1])
    end
  end)
  it("kind inference", function()
    local function kind(attrs) return HA.map_entity({ state = "playing", attributes = attrs }, "http://h", {}, 0).media.kind end
    T.eq(kind({ media_content_type = "app", media_title = "X", media_series_title = "S" }), "episode")
    T.eq(kind({ media_content_type = "video", media_season = "1", media_episode = "3" }), "episode")
    T.eq(kind({ media_content_type = "playlist", media_artist = "A", media_album_name = "B" }), "music")
    T.eq(kind({ media_content_type = "channel" }), "live_tv")
    T.eq(kind({ media_content_type = "video", media_title = "Clip" }), "video")
    T.eq(kind({ media_content_type = "app" }), "unknown")
    T.eq(kind({ media_season = "Specials", media_episode = "x", media_title = "T" }), "unknown")
  end)
  it("401 -> clear error and >= 60s quiet period", function()
    local fd, p = setup(nil, nil, 401)
    local err = poll(fd, p)
    T.contains(err, "rejected the access token")
    T.eq(fd:count("/api/states/"), 1)
    fd:advance(30)
    err = poll(fd, p)
    T.contains(err, "retrying")
    T.eq(fd:count("/api/states/"), 1, "no request during backoff")
    fd:advance(31)
    poll(fd, p)
    T.eq(fd:count("/api/states/"), 2)
  end)
  it("404 -> entity not found", function()
    local fd, p = setup(nil, nil, 404)
    T.contains(poll(fd, p), "entity not found")
  end)
end)
