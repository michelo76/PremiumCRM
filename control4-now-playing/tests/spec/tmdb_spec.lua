local T = ...
local FakeDeps = require("fake_deps")
local Tmdb = require("np.enrich.tmdb")
local pbm = require("np.playback")

local function pb(media, source)
  return pbm.normalize({ source = source or { app_name = "Netflix" }, playback = { state = "playing" }, media = media }, 0)
end

local function run(fd, e, p)
  local r = {}
  e:enrich(p, function(err, partial) r.err, r.partial = err, partial; r.calls = (r.calls or 0) + 1 end, { details = {} })
  fd:flush()
  return r
end

local function movie_routes(fd)
  fd:route("/search/movie", { status = 200, body = T.fixture("tmdb_search_movie_topgun.json") })
  fd:route("/movie/361743", { status = 200, body = T.fixture("tmdb_movie_361743.json") })
end

describe("np.enrich.tmdb", function()
  local fd, e
  before_each(function()
    fd = FakeDeps.new()
    e = Tmdb.new({ api_key = "KEY", language = "en-US", country = "US" }, fd.deps)
  end)

  it("supports only when configured and not music", function()
    T.ok(e:supports(pb({ kind = "movie", title = "Top Gun: Maverick" })))
    T.no(e:supports(pb({ kind = "music", title = "Blinding Lights", artist = "The Weeknd" })))
    T.no(e:supports(pb({ kind = "video" })))
    T.no(Tmdb.new({}, fd.deps):supports(pb({ kind = "movie", title = "X" })))
    T.no(e:supports(pb({ kind = "video", title = "My vlog" }, { app_name = "YouTube" })), "YouTube denied")
  end)

  it("enriches a movie end-to-end", function()
    movie_routes(fd)
    local r = run(fd, e, pb({ kind = "movie", title = "Top Gun: Maverick (2022) [4K]" }))
    T.is_nil(r.err); T.eq(r.calls, 1)
    local s = fd:last("/search/movie").url
    T.contains(s, "query=Top%20Gun%3A%20Maverick"); T.contains(s, "year=2022"); T.contains(s, "api_key=KEY")
    T.contains(fd:last("/movie/361743").url, "append_to_response=credits%2Crelease_dates%2Cexternal_ids%2Cvideos%2Cimages")
    local d = r.partial
    T.eq(d.matched, true); T.gt(d.confidence, 0.9)
    T.eq(d.tagline, "Feel the need... The need for speed.")
    T.eq(d.release_date, "2022-05-21"); T.eq(d.year, 2022); T.eq(d.runtime_min, 131)
    T.eq(d.content_rating, "PG-13")
    T.deep_eq(d.genres, { "Action", "Drama" })
    T.eq(d.poster_url, "https://image.tmdb.org/t/p/w780/62HCnUTziyWcpDaBO2i1DX17ljH.jpg")
    T.eq(d.backdrop_url, "https://image.tmdb.org/t/p/w1280/AaV1YIdWKnjAIAOe8UUKBFm327v.jpg")
    T.eq(d.logo_url, "https://image.tmdb.org/t/p/original/enLogo2.svg", "english logo, best voted, svg->original")
    T.eq(d.ratings.tmdb, 8.2)
    T.eq(d.cast[1].name, "Tom Cruise"); T.eq(d.cast[1].photo_url, "https://image.tmdb.org/t/p/w185/8qBylBsQf4llkGrWR3qAsOtOU8O.jpg")
    T.is_nil(d.cast[4].photo_url); T.eq(d.cast[6].name, "Lewis Pullman", "sorted by order")
    T.deep_eq(d.crew.directors, { "Joseph Kosinski" })
    T.deep_eq(d.crew.writers, { "Ehren Kruger", "Eric Warren Singer", "Christopher McQuarrie", "Peter Craig" })
    T.deep_eq(d.studios, { "Paramount Pictures", "Skydance", "Jerry Bruckheimer Films" })
    T.eq(d.trailer_url, "https://www.youtube.com/watch?v=giXco2jaZ_4")
    T.eq(d.ids.imdb, "tt1745960"); T.eq(d.ids.tmdb, 361743); T.eq(d.links.imdb, "https://www.imdb.com/title/tt1745960/")
    T.eq(d.facts[1].label, "Budget"); T.eq(d.facts[1].value, "$170M")
    T.eq(d.facts[2].value, "$1.49B"); T.eq(d.facts[3].value, "English")
    T.deep_eq(d.attribution, { "TMDB" })
  end)

  it("sends a v4 bearer token instead of api_key", function()
    movie_routes(fd)
    e = Tmdb.new({ bearer = "eyJhbGciOi.v4" }, fd.deps)
    run(fd, e, pb({ kind = "movie", title = "Top Gun: Maverick" }))
    local req = fd:last("/search/movie")
    T.eq(req.headers.Authorization, "Bearer eyJhbGciOi.v4"); T.no(req.url:find("api_key"))
    e = Tmdb.new({ api_key = "eyJhbGciOi.jwt" }, fd.deps)
    run(fd, e, pb({ kind = "movie", title = "Top Gun: Maverick" }))
    T.eq(fd:last("/search/movie").headers.Authorization, "Bearer eyJhbGciOi.jwt")
  end)

  it("retries movie search without year when the year filter finds nothing", function()
    fd:route("/search/movie", { status = 200, body = T.fixture("tmdb_search_movie_topgun.json") })
    fd:route(function(req) return req.url:find("/search/movie", 1, true) and req.url:find("year=2021", 1, true) end,
      FakeDeps.json({ page = 1, results = {}, total_results = 0 }))
    fd:route("/movie/361743", { status = 200, body = T.fixture("tmdb_movie_361743.json") })
    local r = run(fd, e, pb({ kind = "movie", title = "Top Gun: Maverick", year = 2021 }))
    T.eq(fd:count("/search/movie"), 2); T.eq(r.partial.ids.tmdb, 361743)
  end)

  it("prefers the year-matching candidate", function()
    fd:route("/search/movie", { status = 200, body = T.fixture("tmdb_search_movie_topgun.json") })
    fd:route("/movie/744", FakeDeps.json({ id = 744, title = "Top Gun", release_date = "1986-05-16" }))
    local r = run(fd, e, pb({ kind = "movie", title = "Top Gun", year = 1986 }))
    T.eq(r.partial.ids.tmdb, 744)
  end)

  it("enriches an episode with series + episode blocks", function()
    fd:route("/search/tv", { status = 200, body = T.fixture("tmdb_search_tv_bear.json") })
    fd:route("/tv/136315?", { status = 200, body = T.fixture("tmdb_tv_136315.json") })
    fd:route("/tv/136315/season/2/episode/7", { status = 200, body = T.fixture("tmdb_tv_136315_s2e7.json") })
    local r = run(fd, e, pb({ kind = "episode", title = "Forks", series_title = "The Bear", season = 2, episode = 7 }))
    local d = r.partial
    T.eq(d.ids.tmdb, 136315); T.eq(d.ids.imdb, "tt14452776"); T.eq(d.content_rating, "TV-MA")
    T.deep_eq(d.networks, { "Hulu", "FX" }); T.deep_eq(d.crew.creators, { "Christopher Storer" })
    T.deep_eq(d.crew.directors, { "Ramy Youssef" }); T.deep_eq(d.crew.writers, { "Alex O'Keefe" })
    T.eq(d.episode.title, "Forks"); T.eq(d.episode.air_date, "2023-06-22"); T.eq(d.episode.rating, 9.1)
    T.eq(d.episode.still_url, "https://image.tmdb.org/t/p/w780/forksStill.jpg"); T.eq(d.runtime_min, 40)
    T.eq(d.series.seasons, 4); T.eq(d.series.episodes, 38); T.eq(d.series.first_air_date, "2022-06-23")
    T.eq(d.series.next_episode.season, 5); T.eq(d.series.next_episode.air_date, "2026-06-24")
    T.is_nil(d.tagline, "empty tagline -> nil")
    T.eq(d._hints.imdb_episode, "tt26246718")
    T.eq(d.year, 2022)
  end)

  it("parses SxxEyy from an unknown-kind title and takes the tv path", function()
    fd:route("/search/tv", { status = 200, body = T.fixture("tmdb_search_tv_bear.json") })
    fd:route("/tv/136315?", { status = 200, body = T.fixture("tmdb_tv_136315.json") })
    fd:route("/tv/136315/season/2/episode/7", { status = 200, body = T.fixture("tmdb_tv_136315_s2e7.json") })
    local r = run(fd, e, pb({ kind = "video", title = "The Bear S02E07" }, { app_name = "Plex" }))
    T.contains(fd:last("/search/tv").url, "query=The%20Bear"); T.eq(r.partial.episode.title, "Forks")
  end)

  it("episode lookup failure still returns series details", function()
    fd:route("/search/tv", { status = 200, body = T.fixture("tmdb_search_tv_bear.json") })
    fd:route("/tv/136315?", { status = 200, body = T.fixture("tmdb_tv_136315.json") })
    fd:route("/tv/136315/season/9/episode/99", { status = 404, body = '{"success":false,"status_code":34}' })
    local r = run(fd, e, pb({ kind = "episode", series_title = "The Bear", season = 9, episode = 99 }))
    T.is_nil(r.err); T.eq(r.partial.ids.tmdb, 136315); T.is_nil(r.partial.episode)
  end)

  it("/search/multi accepts only high-confidence movie/tv", function()
    fd:route("/search/multi", { status = 200, body = T.fixture("tmdb_search_multi_inception.json") })
    fd:route("/movie/27205", { status = 200, body = T.fixture("tmdb_movie_27205.json") })
    local r = run(fd, e, pb({ kind = "unknown", title = "Inception" }, { app_name = "Plex" }))
    T.eq(r.partial.ids.tmdb, 27205); T.eq(r.partial.ids.imdb, "tt1375666")
    T.deep_eq(r.partial.crew.writers, { "Christopher Nolan" })
  end)

  it("rejects low-confidence multi matches (vlog is not a movie)", function()
    fd:route("/search/multi", { status = 200, body = T.fixture("tmdb_search_multi_vlog.json") })
    local r = run(fd, e, pb({ kind = "video", title = "My Morning Routine" }, { app_name = "Plex" }))
    T.is_nil(r.err); T.is_nil(r.partial); T.eq(fd:count("/movie/"), 0)
  end)

  it("zero results -> no match", function()
    fd:route("/search/movie", FakeDeps.json({ page = 1, results = {}, total_results = 0 }))
    local r = run(fd, e, pb({ kind = "movie", title = "Zzzzz Not A Film" }))
    T.is_nil(r.err); T.is_nil(r.partial)
  end)

  it("401 -> error and 1h block (no further requests)", function()
    fd:route("/search/movie", { status = 401, body = '{"status_code":7,"status_message":"Invalid API key: You must be granted a valid key."}' })
    local r = run(fd, e, pb({ kind = "movie", title = "Top Gun: Maverick" }))
    T.contains(r.err, "TMDB"); T.contains(r.err, "401")
    r = run(fd, e, pb({ kind = "movie", title = "Top Gun: Maverick" }))
    T.contains(r.err, "API key rejected"); T.eq(fd:count("/search/movie"), 1)
    fd:advance(3601)
    run(fd, e, pb({ kind = "movie", title = "Top Gun: Maverick" }))
    T.eq(fd:count("/search/movie"), 2)
  end)

  it("429 -> honours Retry-After", function()
    fd:route("/search/movie", { status = 429, headers = { ["Retry-After"] = "10" }, body = "" })
    local r = run(fd, e, pb({ kind = "movie", title = "Top Gun: Maverick" }))
    T.contains(r.err, "rate limited")
    run(fd, e, pb({ kind = "movie", title = "Top Gun: Maverick" }))
    T.eq(fd:count("/search/movie"), 1)
    fd:advance(11); movie_routes(fd)
    r = run(fd, e, pb({ kind = "movie", title = "Top Gun: Maverick" }))
    T.is_nil(r.err); T.ok(r.partial)
  end)

  it("500, garbage body and transport errors are errors (no crash)", function()
    fd:route("/search/movie", { status = 500, body = "Internal" })
    T.contains(run(fd, e, pb({ kind = "movie", title = "A" })).err, "500")
    fd:route("/search/movie", { status = 200, body = "<html>cloudflare</html>" })
    T.contains(run(fd, e, pb({ kind = "movie", title = "A" })).err, "invalid JSON")
    fd:route("/search/movie", { err = "timeout" })
    T.contains(run(fd, e, pb({ kind = "movie", title = "A" })).err, "timeout")
    fd:route("/search/movie", { status = 200, body = T.fixture("tmdb_search_movie_topgun.json") })
    fd:route("/movie/361743", { status = 502, body = "" })
    T.contains(run(fd, e, pb({ kind = "movie", title = "Top Gun: Maverick" })).err, "502")
  end)
end)
