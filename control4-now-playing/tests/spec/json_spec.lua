local T = ...
local json = require("np.json")

describe("np.json", function()
  it("round-trips nested values", function()
    local s = json.encode({ a = 1, b = { 1, 2, 3 }, c = "x\"y\n", d = true, e = 1.5 })
    T.eq(s, '{"a":1,"b":[1,2,3],"c":"x\\"y\\n","d":true,"e":1.5}')
    local v = json.decode(s)
    T.eq(v.c, "x\"y\n"); T.eq(v.b[3], 3); T.eq(v.e, 1.5)
  end)
  it("distinguishes empty array and empty object via marks", function()
    T.eq(json.encode(json.array({})), "[]")
    T.eq(json.encode(json.object({})), "{}")
    T.eq(json.encode({}), "{}")
    T.eq(json.encode(json.decode("[]")), "[]", "decoded arrays keep their mark")
    T.eq(json.encode(json.decode("{}")), "{}")
  end)
  it("encodes null sentinel and nil", function()
    T.eq(json.encode({ a = json.null }), '{"a":null}')
    T.eq(json.encode(nil), "null")
  end)
  it("honours explicit key order", function()
    T.eq(json.encode(json.ordered({ z = 1, a = 2, m = 3 }, { "z", "a" })), '{"z":1,"a":2,"m":3}')
  end)
  it("decodes unicode escapes and surrogate pairs", function()
    T.eq(json.decode('"caf\\u00e9 \\ud83c\\udfac"'), "café 🎬")
  end)
  it("integers vs floats, NaN/inf as null", function()
    T.eq(json.encode(1790000000), "1790000000")
    T.eq(json.encode(0.1), "0.1")
    T.eq(json.encode(0 / 0), "null")
    T.eq(json.encode(math.huge), "null")
  end)
  it("returns nil, err on garbage", function()
    local v, err = json.decode("<html>502 Bad Gateway</html>")
    T.is_nil(v); T.contains(err, "json")
    v, err = json.decode('{"a":1')
    T.is_nil(v); T.ok(err)
    v, err = json.decode('{"a":1} x')
    T.is_nil(v); T.contains(err, "trailing")
    v, err = json.decode(nil)
    T.is_nil(v); T.ok(err)
  end)
  it("decodes numbers with exponents and negatives", function()
    local v = json.decode('[-1.5e3, 2E-2, 0]')
    T.eq(v[1], -1500); T.near(v[2], 0.02); T.eq(v[3], 0)
  end)
  it("rejects cycles without crashing", function()
    local t = {}; t.self = t
    local s, err = json.encode(t)
    T.is_nil(s); T.contains(err, "circular")
  end)
end)
