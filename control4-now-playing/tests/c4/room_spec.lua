local T = ...
local Room = require("c4.room")
local b64 = require("c4.b64")

local P = Room.parse_media_info

describe("c4.b64", function()
  it("round-trips binary data", function()
    local s = ""
    for i = 0, 255 do s = s .. string.char(i) end
    for _, x in ipairs({ "", "f", "fo", "foo", "foob", "fooba", "foobar", s }) do
      T.eq(b64.decode(b64.encode(x)) or "", x)
    end
    T.eq(b64.encode("foobar"), "Zm9vYmFy")
    T.eq(b64.encode("fo"), "Zm8=")
    T.is_nil(b64.decode("not base64!"))
  end)
end)

describe("c4.room.parse_media_info", function()
  it("UPDATE_MEDIA_INFO style upper-case tags with a plain IMAGEURL", function()
    local i = P("<mediainfo><TITLE>Blinding Lights</TITLE><ARTIST>The Weeknd</ARTIST><ALBUM>After Hours</ALBUM>" ..
      "<GENRE>Pop</GENRE><IMAGEURL>http://192.168.1.20/art/1.jpg</IMAGEURL></mediainfo>")
    T.deep_eq(i, { title = "Blinding Lights", artist = "The Weeknd", album = "After Hours", genre = "Pop",
      image = "http://192.168.1.20/art/1.jpg" })
  end)
  it("base64-encoded IMAGEURL", function()
    local enc = b64.encode("https://cdn.example.com/cover.png")
    local i = P("<media><title>Song</title><artist>Band</artist><imageurl>" .. enc .. "</imageurl></media>")
    T.eq(i.image, "https://cdn.example.com/cover.png")
  end)
  it("base64 that does not decode to a URL is dropped", function()
    local i = P("<media><title>Song</title><imageurl>" .. b64.encode("\0\1binary") .. "</imageurl></media>")
    T.eq(i.title, "Song"); T.is_nil(i.image)
    T.is_nil(P("<media><title>Song</title><img>/relative/path.jpg</img></media>").image)
  end)
  it("LINE1/LINE2/LINE3", function()
    local i = P("<info><line1>Morning Edition</line1><line2>NPR</line2><line3>KQED</line3></info>")
    T.deep_eq(i, { title = "Morning Edition", artist = "NPR", album = "KQED" })
  end)
  it("explicit TITLE beats LINE1 regardless of order", function()
    local i = P("<x><line1>L1</line1><title>Real</title></x>")
    T.eq(i.title, "Real")
  end)
  it("XML entities, CDATA, namespaces, attributes, escaped XML", function()
    T.eq(P("<a><title>Tom &amp; Jerry &#233;</title></a>").title, "Tom & Jerry é")
    T.eq(P("<a><title><![CDATA[Rock & <Roll>]]></title></a>").title, "Rock & <Roll>")
    T.eq(P("<ns:media><ns:Title>NS</ns:Title></ns:media>").title, "NS")
    local a = P('<media title="Attr Title" artist="Attr Artist" image="http://10.0.0.2/a.png"/>')
    T.deep_eq(a, { title = "Attr Title", artist = "Attr Artist", image = "http://10.0.0.2/a.png" })
    T.eq(P("&lt;media&gt;&lt;title&gt;Escaped&lt;/title&gt;&lt;/media&gt;").title, "Escaped")
    T.eq(P('<item name="TITLE">Named</item>').title, "Named")
  end)
  it("JSON media info", function()
    local i = P('{"Title":"J","Artist":"K","ImageUrl":"http://x.local/a.jpg"}')
    T.deep_eq(i, { title = "J", artist = "K", image = "http://x.local/a.jpg" })
  end)
  it("empty / garbage / image-only -> nil", function()
    T.is_nil(P(nil)); T.is_nil(P("")); T.is_nil(P("   "))
    T.is_nil(P("<mediainfo></mediainfo>"))
    T.is_nil(P("<mediainfo><TITLE></TITLE><ARTIST> </ARTIST></mediainfo>"))
    T.is_nil(P("garbage <<<>>> ")); T.is_nil(P("{not json")); T.is_nil(P("<<title>"))
    T.is_nil(P("<m><imageurl>http://a/b.jpg</imageurl></m>"))
    T.is_nil(P("<m><title>null</title></m>"))
  end)
end)

describe("c4.room playback mapping", function()
  local V = Room.VAR
  it("is_on: POWER_STATE variants, fallback to selected device", function()
    T.eq(Room.is_on({ [V.POWER] = "1" }), true)
    T.eq(Room.is_on({ [V.POWER] = "ON" }), true)
    T.eq(Room.is_on({ [V.POWER] = "0" }), false)
    T.eq(Room.is_on({ [V.POWER] = "Off" }), false)
    T.eq(Room.is_on({ [V.SELECTED] = "245" }), true)
    T.eq(Room.is_on({ [V.SELECTED] = "0" }), false)
    T.is_nil(Room.is_on({}))
    T.eq(Room.is_on({ [V.POWER] = "weird", [V.SELECTED] = "12" }), true)
  end)
  it("on + music info -> playing music", function()
    local pb = Room.to_playback({ [V.POWER] = "1", [V.MEDIA_INFO] = "<x><TITLE>T</TITLE><ARTIST>A</ARTIST><GENRE>Jazz</GENRE></x>" }, "Sonos", 5)
    T.eq(pb.playback.state, "playing"); T.eq(pb.media.kind, "music")
    T.eq(pb.media.title, "T"); T.deep_eq(pb.media.genres, { "Jazz" })
    T.eq(pb.source.provider, "c4room"); T.eq(pb.source.device_name, "Sonos")
  end)
  it("on + title only -> playing unknown; on + nothing -> idle; off -> off", function()
    T.eq(Room.to_playback({ [V.POWER] = "1", [V.MEDIA_INFO] = "<x><TITLE>T</TITLE></x>" }).media.kind, "unknown")
    T.eq(Room.to_playback({ [V.POWER] = "1", [V.MEDIA_INFO] = "" }).playback.state, "idle")
    T.eq(Room.to_playback({ [V.POWER] = "0", [V.MEDIA_INFO] = "<x><TITLE>T</TITLE></x>" }).playback.state, "off")
  end)
end)
