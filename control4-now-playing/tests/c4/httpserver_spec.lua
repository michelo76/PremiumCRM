local T = ...
local Server = require("c4.httpserver")
local Deps = require("c4.deps")

describe("c4.httpserver.parse_request", function()
  it("parses request line, path and headers", function()
    local r = Server.parse_request("GET /api/state?x=1 HTTP/1.1\r\nHost: a\r\nIf-None-Match: \"1-abc\"\r\n\r\n")
    T.eq(r.method, "GET"); T.eq(r.path, "/api/state"); T.eq(r.headers["if-none-match"], '"1-abc"')
    T.eq(Server.parse_request("GET / HTTP/1.0\n\n").path, "/")
    local _, err = Server.parse_request("GET / HTTP/1.1\r\n")
    T.eq(err, "incomplete")
    T.is_nil(Server.parse_request("garbage\r\n\r\n"))
  end)
end)

describe("c4.deps helpers", function()
  it("redacts keys and tokens from URLs and literal secrets", function()
    local r = Deps.redact("GET https://api.themoviedb.org/3/x?api_key=abc123&query=x " ..
      "http://o/?apikey=zzz&i=1 http://b/a?v=1&token=sekrit Authorization: Bearer eyJabc.def MYSECRET", { "MYSECRET" })
    T.no(r:find("abc123")); T.no(r:find("zzz")); T.no(r:find("sekrit")); T.no(r:find("eyJabc"))
    T.no(r:find("MYSECRET"))
    local u = Deps.redact("URL_CHANGED controller://driver/x/index.html?relay=http%3A%2F%2F1.2.3.4%3A8487&k=SeCrEt-123_x")
    T.no(u:find("SeCrEt", 1, true)); T.contains(u, "relay=http%3A")
    T.contains(r, "query=x"); T.contains(r, "i=1")
  end)
  it("debug mode flags", function()
    T.deep_eq({ Deps.mode_flags("Off") }, { false, false })
    T.deep_eq({ Deps.mode_flags("Print") }, { true, false })
    T.deep_eq({ Deps.mode_flags("Log") }, { false, true })
    T.deep_eq({ Deps.mode_flags("Print and Log") }, { true, true })
  end)
end)

describe("c4.httpserver query / token helpers", function()
  it("parse_request exposes the decoded query", function()
    local r = Server.parse_request("GET /api/artwork?url=http%3A%2F%2F192.168.1.10%2Fa.png%3Fv%3D1&k=abc+d HTTP/1.1\r\n\r\n")
    T.eq(r.path, "/api/artwork")
    T.eq(r.query.url, "http://192.168.1.10/a.png?v=1"); T.eq(r.query.k, "abc d")
    T.deep_eq(Server.parse_query("a=1&b=&c&a=2"), { a = "1", b = "", c = "" })
  end)
  it("token_eq: exact match only, empty expected never matches", function()
    T.ok(Server.token_eq("Secr3t-token_xyz", "Secr3t-token_xyz"))
    T.no(Server.token_eq("Secr3t-token_xy", "Secr3t-token_xyz"))
    T.no(Server.token_eq("Secr3t-token_xyzz", "Secr3t-token_xyz"))
    T.no(Server.token_eq("Xecr3t-token_xyz", "Secr3t-token_xyz"))
    T.no(Server.token_eq(nil, "Secr3t-token_xyz"))
    T.no(Server.token_eq("", "")); T.no(Server.token_eq("x", nil))
  end)
end)

describe("c4.httpserver against the C4 mock (CreateServer / DestroyServer / idle clients)", function()
  local Mock = require("c4_mock")
  local TOKEN = "tok-0123456789abcdef"
  local function setup(opts)
    opts = opts or {}
    local m = Mock.new({ root = T.root .. "/driver" })
    m:activate()
    m.phase = "running"
    for k, v in pairs(opts.mock or {}) do m[k] = v end
    local deps = Deps.new(m.C4, {})
    local events = {}
    local S = Server.new(m.C4, deps, {
      state = function() return '{"schema":1}', '"1-x"' end,
      index = function() return "<!doctype html>" end,
      token = function() return TOKEN end,
      artwork = opts.artwork,
      on_listen = function(ok, port, err) events[#events + 1] = { ok = ok, port = port, err = err } end,
    })
    -- the driver's entry points, as driver.lua forwards them (identifier appended, OS 3.3.1+)
    m.env = {
      OnServerDataIn = function(...) S:on_data(...) end,
      OnServerConnectionStatusChanged = function(...) S:on_status(...) end,
    }
    return m, S, events
  end
  local function get(m, h, target)
    m:connect(h); m:client_send(h, "GET " .. target .. " HTTP/1.1\r\n\r\n")
    return m:response(h)
  end

  it("uses CreateServer(port, '', false, identifier) and DestroyServer(port)", function()
    local m, S, ev = setup()
    T.eq(S:start(8487), true)
    T.eq(m.server.port, 8487); T.eq(m.server.identifier, Server.IDENTIFIER); T.eq(m.server.delimiter, "")
    T.eq(m.server.udp, false)
    T.ok(ev[#ev].ok)
    S:stop()
    T.is_nil(m.server, "DestroyServer(port) destroyed the listener")
    T.eq(#m.misuse, 0, table.concat(m.misuse, ","))
    m:deactivate()
  end)
  it("falls back to CreateServer(port) on an OS without the identifier argument", function()
    local m, S = setup({ mock = { legacy_create_server = true } })
    T.eq(S:start(8487), true)
    T.eq(m.server.port, 8487); T.is_nil(m.server.identifier)
    T.ok(get(m, 1, "/api/state?k=" .. TOKEN):find("^HTTP/1.1 200"))
    m:deactivate()
  end)
  it("CreateServer returning false, err: not listening, error reported, retried with backoff", function()
    local m, S, ev = setup({ mock = { create_server_fail = { "Address already in use", "Address already in use" } } })
    local ok, err = S:start(8487)
    T.eq(ok, false); T.eq(err, "Address already in use")
    T.no(S.listening); T.eq(S.last_error, "Address already in use"); T.is_nil(m.server)
    T.eq(ev[#ev].ok, false); T.eq(ev[#ev].err, "Address already in use")
    T.eq(select(1, S:start(8487)), false, "same port while retrying: no new attempt")
    m:advance(4.9); T.is_nil(m.server)
    m:advance(0.2); T.is_nil(m.server, "2nd attempt (5 s) fails too")
    m:advance(9.8); T.is_nil(m.server)
    m:advance(0.3)
    T.eq(m.server and m.server.port, 8487, "3rd attempt after 10 more s")
    T.ok(S.listening); T.is_nil(S.last_error); T.ok(ev[#ev].ok)
    T.eq(m:pending_timers(), 0, "no retry timer left")
    m:deactivate()
  end)
  it("ignores data / status for another server identifier", function()
    local m, S = setup()
    S:start(8487)
    m:connect(1)
    m:client_send(1, "GET /api/state?k=" .. TOKEN .. " HTTP/1.1\r\n\r\n", "someone-elses-server")
    T.is_nil(m.sent[1])
    m:client_send(1, "GET /api/state?k=" .. TOKEN .. " HTTP/1.1\r\n\r\n")
    T.ok(m:response(1):find("^HTTP/1.1 200"))
    m:deactivate()
  end)
  it("closes a client that sends no complete request within 10 s; buffers and timers freed", function()
    local m, S = setup()
    S:start(8487)
    m:connect(1)                         -- connects, sends nothing
    m:connect(2); m:client_send(2, "GET /api/sta") -- stalls mid-request
    m:connect(3); m:client_send(3, "GET /api/state?k=" .. TOKEN .. " HTTP/1.1\r\n\r\n")
    T.ok(m.closed[3])
    m:advance(9.5)
    T.no(m.closed[1]); T.no(m.closed[2])
    m:advance(1)
    T.ok(m.closed[1]); T.ok(m.closed[2])
    T.ok(m:response(2):find("^HTTP/1.1 408"))
    T.eq(S.nbuf, 0); T.is_nil(next(S.buffers)); T.is_nil(next(S.idle))
    T.eq(m:pending_timers(), 0)
    m:deactivate()
  end)
  it("token required on /api/state and /api/artwork (401), not on / ; ?inm= works like If-None-Match", function()
    local m, S = setup({ artwork = function(url, cb) cb(200, { ["Content-Type"] = "image/png" }, "PNGDATA") end })
    S:start(8487)
    local r = get(m, 1, "/api/state")
    T.ok(r:find("^HTTP/1.1 401 Unauthorized")); T.contains(r, '"error":"unauthorized"')
    T.ok(get(m, 2, "/api/state?k=wrong-0123456789abc"):find("^HTTP/1.1 401"))
    T.ok(get(m, 3, "/api/artwork?url=http%3A%2F%2F192.168.1.2%2Fa.png"):find("^HTTP/1.1 401"))
    T.ok(get(m, 4, "/"):find("^HTTP/1.1 200"))
    r = get(m, 5, "/api/state?k=" .. TOKEN)
    T.ok(r:find("^HTTP/1.1 200")); T.contains(r, "Access-Control-Expose-Headers: ETag, Date")
    T.ok(get(m, 6, "/api/state?k=" .. TOKEN .. "&inm=%221-x%22"):find("^HTTP/1.1 304"))
    r = get(m, 7, "/api/artwork?url=http%3A%2F%2F192.168.1.2%2Fa.png&k=" .. TOKEN)
    T.ok(r:find("^HTTP/1.1 200")); T.contains(r, "Content-Type: image/png"); T.eq(r:match("\r\n\r\n(.*)$"), "PNGDATA")
    m:connect(8); m:client_send(8, "OPTIONS /api/state HTTP/1.1\r\nOrigin: controller://x\r\n\r\n")
    r = m:response(8)
    T.ok(r:find("^HTTP/1.1 204")); T.contains(r, "Access-Control-Allow-Headers: If-None-Match")
    m:deactivate()
  end)
  it("async artwork answer after the client went away is dropped (handle reuse safe)", function()
    local pending
    local m, S = setup({ artwork = function(url, cb) pending = cb end })
    S:start(8487)
    m:connect(1); m:client_send(1, "GET /api/artwork?url=http%3A%2F%2F10.0.0.2%2Fa.png&k=" .. TOKEN .. " HTTP/1.1\r\n\r\n")
    T.is_nil(m.sent[1])
    m:client_close(1)
    m:connect(1) -- handle number reused by a new client
    pending(200, { ["Content-Type"] = "image/png" }, "LATE")
    T.is_nil(m.sent[1], "the late answer must not reach the new client")
    m:advance(11)
    T.ok(m:response(1):find("^HTTP/1.1 408"))
    m:deactivate()
  end)
end)
