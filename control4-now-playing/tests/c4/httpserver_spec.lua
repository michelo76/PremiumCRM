local T = ...
local Server = require("c4.httpserver")
local Deps = require("c4.deps")

describe("c4.httpserver.parse_request", function()
  it("parses request line, path and headers", function()
    local r = Server.parse_request("GET /api/state?x=1 HTTP/1.1\r\nHost: a\r\nIf-None-Match: \"1-abc\"\r\n\r\n")
    T.eq(r.method, "GET"); T.eq(r.path, "/api/state"); T.eq(r.headers["if-none-match"], '"1-abc"')
    T.eq(Server.parse_request("GET / HTTP/1.0\n\n").path, "/")
    local _, err = Server.parse_request("GET / HTTP/1.1\r\n")
    T.eq(err, "incomplete")
    T.is_nil(Server.parse_request("garbage\r\n\r\n"))
  end)
end)

describe("c4.deps helpers", function()
  it("redacts keys and tokens from URLs and literal secrets", function()
    local r = Deps.redact("GET https://api.themoviedb.org/3/x?api_key=abc123&query=x " ..
      "http://o/?apikey=zzz&i=1 http://b/a?v=1&token=sekrit Authorization: Bearer eyJabc.def MYSECRET", { "MYSECRET" })
    T.no(r:find("abc123")); T.no(r:find("zzz")); T.no(r:find("sekrit")); T.no(r:find("eyJabc"))
    T.no(r:find("MYSECRET"))
    T.contains(r, "query=x"); T.contains(r, "i=1")
  end)
  it("debug mode flags", function()
    T.deep_eq({ Deps.mode_flags("Off") }, { false, false })
    T.deep_eq({ Deps.mode_flags("Print") }, { true, false })
    T.deep_eq({ Deps.mode_flags("Log") }, { false, true })
    T.deep_eq({ Deps.mode_flags("Print and Log") }, { true, true })
  end)
end)
